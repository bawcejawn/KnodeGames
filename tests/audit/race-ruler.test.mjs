test("publish: a switch change that would change how a started week is scored is refused, and nothing is published", async () => {
  const bare = bareRepo();
  // unset → 3 during week 2: week 2 becomes shadow (counts for nothing), on from week 3: allowed
  assert.ok(publish(await mondayRace(3, []), bare, NOW, { RACE_RULER_FROM_WEEK: "3" }).ok);
  // 3 → 2 during week 2: week 2 (started) would become ON: refused
  const on = await mondayRace(2, []);
  const before = published(bare, "W002.json"), r = publish(on, bare, NOW + 2 * H, { RACE_RULER_FROM_WEEK: "2" });
  assert.equal(r.ok, false); assert.match(r.out, /ruler switch change is refused/);
  assert.equal(published(bare, "W002.json"), before, "nothing published");
  // a first switch-on to the running week from unset: refused too
  // a first switch-on into the running week, with no ruler file published before (unset): refused too
  const r2 = publish(on, bareRepo(), NOW, { RACE_RULER_FROM_WEEK: "2" });
  assert.equal(r2.ok, false); assert.match(r2.out, /moved from unset to 2: week 2 has started/);
  // back to unset from 3 during week 2 (shadow → off): allowed (shadow counts for nothing)
  const offRun = await mondayRace(null, []);
  assert.ok(publish(offRun, bare, NOW + 3 * H, { RACE_RULER_FROM_WEEK: "" }).ok);
});

