// Writes .github/workflows/vhp-ruler.yml with vhp_ruler.py embedded in its publish step (the publish job runs no repo
// code: RECORDER_STANDARD §6). Run after any change to vhp_ruler.py:  node tools/vhp-ruler-workflow.mjs
// A test (tests/audit/vhp-ruler.workflow.test.mjs) fails if the embedded copy differs from vhp_ruler.py by one byte.
import fs from "node:fs";
const root = new URL("..", import.meta.url).pathname;
const py = fs.readFileSync(root + "vhp_ruler.py", "utf8");
export const TRAILER = "\nimport sys\nsys.exit(publish_main(sys.argv[1:]))\n";
const IND = "          ";
const body = (py + TRAILER).split("\n").map((l) => (l ? IND + l : l)).join("\n");
const CHECKOUT = "actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4.4.0";
const NODE = "actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020 # v4.4.0";
const UP = "actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02 # v4.6.2";
const DOWN = "actions/download-artifact@d3f86a106a0bac45b974a628896c90dbdf5c8093 # v4.3.0";
const yml = `# The shared VHP ruler's data (design .ai/standards/VHP_RULER.md §7, D-111, D-112). READ-ONLY on the chain: no key,
# no secret, no Mana. GENERATED by tools/vhp-ruler-workflow.mjs (the publish step embeds vhp_ruler.py): edit that file
# and the generator, never this one by hand.
#  - record (hourly): the next irreversible block-hours, read on two nodes (bot/vhp-ruler.ts).
#  - fill (by hand, once): the first 30 days (bot/vhp-fill.ts): a plan, three parallel jobs of 10 days each (a failed
#    one is re-run alone with "Re-run failed jobs"), then one live read and the hour files.
#  - publish: runs NO repository code. The embedded vhp_ruler.py checks every new file (hash chain, one signer and one
#    burn per block, every balance adding up to the hour before, write-once, canonical names, rollups, retention), then
#    reads every new block's id and signer again itself (on vars.RPC_VERIFY if set, else RPC_CHECK: the record job
#    runs repo code and npm packages, this job runs neither), and only then pushes to vhp-data.
# Off until the owner sets the repository variable VHP_RULER_ENABLED to true (after Repo Lens review 2).
name: VHP ruler data

on:
  schedule:
    - cron: "12 * * * *"     # every hour at minute 12
  workflow_dispatch:
    inputs:
      mode:
        description: "record (the next hours) or fill (the first 30 days, once)"
        required: true
        default: record
        type: choice
        options: [record, fill]

concurrency:
  group: knode-vhp-ruler
  cancel-in-progress: false

permissions:
  contents: read

jobs:
  record:
    if: \${{ vars.VHP_RULER_ENABLED == 'true' && github.ref == 'refs/heads/main' && (github.event_name == 'schedule' || inputs.mode == 'record') }}
    runs-on: ubuntu-latest
    timeout-minutes: 30
    permissions:
      contents: read
    steps:
      - uses: ${CHECKOUT}
        with:
          ref: main
          persist-credentials: false
      - uses: ${NODE}
        with:
          node-version: 22
      - run: npm ci --no-audit --no-fund --ignore-scripts
      - name: Take the published hours
        run: |
          set -euo pipefail
          mkdir -p "$RUNNER_TEMP/prev/h" "$RUNNER_TEMP/prev/d"
          url="https://github.com/\${GITHUB_REPOSITORY}.git"
          rc=0; git ls-remote --exit-code "$url" refs/heads/vhp-data >/dev/null 2>&1 || rc=$?
          if [ "$rc" = 2 ]; then echo "::error::No vhp-data branch yet: run this workflow with mode fill first."; exit 1; fi
          if [ "$rc" != 0 ]; then echo "::error::Couldn't read the vhp-data branch (git ls-remote exit $rc)"; exit 1; fi
          git init -q prev-repo && git -C prev-repo fetch -q --depth 1 "$url" vhp-data
          git -C prev-repo ls-tree -r -z --name-only FETCH_HEAD > "$RUNNER_TEMP/files"
          while IFS= read -r -d '' f; do
            if [[ "$f" =~ ^h/(0|[1-9][0-9]{0,8})\\.json$ ]]; then git -C prev-repo show "FETCH_HEAD:$f" > "$RUNNER_TEMP/prev/$f"; fi
            if [[ "$f" =~ ^d/(0|[1-9][0-9]{0,8})\\.json$ ]]; then : > "$RUNNER_TEMP/prev/$f"; fi   # names only: the recorder needs which days exist
          done < "$RUNNER_TEMP/files"
      - name: Record the next hours
        run: npx tsx bot/vhp-ruler.ts
        env:
          RPC: \${{ vars.RPC || 'https://koinos.armana.io' }}
          RPC_CHECK: \${{ vars.RPC_CHECK || 'https://api.koinosblocks.com' }}
          VHP_PREV: \${{ runner.temp }}/prev
          VHP_OUT: \${{ runner.temp }}/vhp-out
          VHP_KEEP_DAYS: \${{ vars.VHP_KEEP_DAYS || '30' }}
      - uses: ${UP}
        with:
          name: vhp-out
          path: \${{ runner.temp }}/vhp-out/
          retention-days: 1
          if-no-files-found: ignore

  fill-plan:
    if: \${{ vars.VHP_RULER_ENABLED == 'true' && github.ref == 'refs/heads/main' && inputs.mode == 'fill' }}
    runs-on: ubuntu-latest
    timeout-minutes: 10
    permissions:
      contents: read
    steps:
      - uses: ${CHECKOUT}
        with:
          ref: main
          persist-credentials: false
      - uses: ${NODE}
        with:
          node-version: 22
      - run: npm ci --no-audit --no-fund --ignore-scripts
      - name: Refuse if vhp-data already exists (the fill runs once)
        run: |
          set -euo pipefail
          rc=0; git ls-remote --exit-code "https://github.com/\${GITHUB_REPOSITORY}.git" refs/heads/vhp-data >/dev/null 2>&1 || rc=$?
          if [ "$rc" = 0 ]; then echo "::error::vhp-data already exists; the first fill runs only once."; exit 1; fi
          if [ "$rc" != 2 ]; then echo "::error::Couldn't read the branches (git ls-remote exit $rc)"; exit 1; fi
      - name: Fix the hours to fill
        run: npx tsx bot/vhp-fill.ts
        env:
          FILL_PART: plan
          RPC: \${{ vars.RPC || 'https://koinos.armana.io' }}
          RPC_CHECK: \${{ vars.RPC_CHECK || 'https://api.koinosblocks.com' }}
          FILL_STATE: \${{ runner.temp }}/fill-state
          FILL_DAYS: "30"
      - uses: ${UP}
        with:
          name: fill-plan
          path: \${{ runner.temp }}/fill-state/plan.json
          retention-days: 3

  fill-chunks:
    needs: fill-plan
    if: \${{ vars.VHP_RULER_ENABLED == 'true' && github.ref == 'refs/heads/main' && inputs.mode == 'fill' }}
    runs-on: ubuntu-latest
    timeout-minutes: 340
    permissions:
      contents: read
    strategy:
      fail-fast: false
      matrix:
        part: [{ from: 0, to: 9 }, { from: 10, to: 19 }, { from: 20, to: 29 }]   # three jobs, 10 days each; a failed one is re-run alone
    steps:
      - uses: ${CHECKOUT}
        with:
          ref: main
          persist-credentials: false
      - uses: ${NODE}
        with:
          node-version: 22
      - run: npm ci --no-audit --no-fund --ignore-scripts
      - uses: ${DOWN}
        with:
          name: fill-plan
          path: \${{ runner.temp }}/fill-state
      - name: Read the days on both nodes
        run: npx tsx bot/vhp-fill.ts
        env:
          FILL_PART: chunks
          FILL_CHUNK_FROM: \${{ matrix.part.from }}
          FILL_CHUNK_TO: \${{ matrix.part.to }}
          RPC: \${{ vars.RPC || 'https://koinos.armana.io' }}
          RPC_CHECK: \${{ vars.RPC_CHECK || 'https://api.koinosblocks.com' }}
          FILL_STATE: \${{ runner.temp }}/fill-state
      - uses: ${UP}
        with:
          name: fill-chunks-\${{ matrix.part.from }}
          path: \${{ runner.temp }}/fill-state/c*.json
          retention-days: 3

  fill-hours:
    needs: fill-chunks
    if: \${{ vars.VHP_RULER_ENABLED == 'true' && github.ref == 'refs/heads/main' && inputs.mode == 'fill' }}
    runs-on: ubuntu-latest
    timeout-minutes: 60
    permissions:
      contents: read
    steps:
      - uses: ${CHECKOUT}
        with:
          ref: main
          persist-credentials: false
      - uses: ${NODE}
        with:
          node-version: 22
      - run: npm ci --no-audit --no-fund --ignore-scripts
      - uses: ${DOWN}
        with:
          pattern: fill-*
          merge-multiple: true
          path: \${{ runner.temp }}/fill-state
      - name: One live read, then the hour files
        run: npx tsx bot/vhp-fill.ts
        env:
          FILL_PART: hours
          RPC: \${{ vars.RPC || 'https://koinos.armana.io' }}
          RPC_CHECK: \${{ vars.RPC_CHECK || 'https://api.koinosblocks.com' }}
          FILL_STATE: \${{ runner.temp }}/fill-state
          VHP_OUT: \${{ runner.temp }}/vhp-out
      - uses: ${UP}
        with:
          name: vhp-out
          path: \${{ runner.temp }}/vhp-out/
          retention-days: 1

  publish:
    needs: [record, fill-hours]
    if: \${{ always() && vars.VHP_RULER_ENABLED == 'true' && github.ref == 'refs/heads/main' && (needs.record.result == 'success' || needs.fill-hours.result == 'success') }}
    runs-on: ubuntu-latest
    timeout-minutes: 90       # the first fill's 30 days are checked block by block
    permissions:
      contents: write         # push the vhp-data branch (never main)
    steps:
      - uses: ${DOWN}
        continue-on-error: true
        with:
          name: vhp-out
          path: \${{ runner.temp }}/incoming
      - name: Check and push vhp-data (and nothing else)
        env:
          GH_TOKEN: \${{ github.token }}
          IN: \${{ runner.temp }}/incoming
          KEEP: \${{ vars.VHP_KEEP_DAYS || '30' }}
          RPC: \${{ vars.RPC || 'https://koinos.armana.io' }}
          RPC_CHECK: \${{ vars.RPC_CHECK || 'https://api.koinosblocks.com' }}
          RPC_VERIFY: \${{ vars.RPC_VERIFY || '' }}
        run: |
          set -euo pipefail
          if [ ! -d "$IN" ]; then echo "Nothing to publish."; exit 0; fi
          bad=$(find "$IN" -mindepth 1 \\( -type l -o \\( -type d ! -path "$IN/h" ! -path "$IN/d" \\) -o \\( -type f ! -regex "$IN/[hd]/\\(0\\|[1-9][0-9]*\\)\\.json" ! -path "$IN/remove.txt" \\) \\) -print)
          if [ -n "$bad" ]; then echo "::error::Refusing to publish unexpected files: $bad"; exit 1; fi
          remote="https://x-access-token:\${GH_TOKEN}@github.com/\${GITHUB_REPOSITORY}.git"
          git init -q work
          parent=""
          mkdir -p "$RUNNER_TEMP/published"
          if git -C work fetch -q --depth 1 "$remote" vhp-data 2>/dev/null; then
            parent=$(git -C work rev-parse FETCH_HEAD)
            git -C work ls-tree -r -z --name-only FETCH_HEAD > "$RUNNER_TEMP/pubfiles"
            while IFS= read -r -d '' f; do
              if [[ "$f" =~ ^[hd]/(0|[1-9][0-9]{0,8})\\.json$ ]]; then mkdir -p "$RUNNER_TEMP/published/\${f%/*}"; git -C work show "FETCH_HEAD:$f" > "$RUNNER_TEMP/published/$f"; fi
            done < "$RUNNER_TEMP/pubfiles"
          fi
          /usr/bin/python3 -I -B - "$IN" "$RUNNER_TEMP/published" "$KEEP" <<'PY'
${body}          PY
          # the checks passed: the published files, plus the new ones, minus the removals
          mkdir -p tree && cp -R "$RUNNER_TEMP/published/." tree/ 2>/dev/null || true
          for d in h d; do if [ -d "$IN/$d" ]; then mkdir -p "tree/$d"; cp "$IN/$d/"*.json "tree/$d/"; fi; done
          if [ -f "$IN/remove.txt" ]; then while IFS= read -r f || [ -n "$f" ]; do [ -n "$f" ] && rm -f "tree/$f"; done < "$IN/remove.txt"; fi
          cd tree
          git init -q -b vhp-data
          git -c user.name="knode-vhp-ruler" -c user.email="knode-vhp-ruler@users.noreply.github.com" add -A
          tree_id=$(git write-tree)
          count() { if [ -d "$1" ]; then find "$1" -name '*.json' | wc -l; else echo 0; fi; }
          msg="vhp-data: $(count "$IN/h") hour(s), $(count "$IN/d") day(s)"
          if [ -n "$parent" ]; then
            git fetch -q --depth 1 "$remote" vhp-data
            commit=$(git -c user.name="knode-vhp-ruler" -c user.email="knode-vhp-ruler@users.noreply.github.com" commit-tree "$tree_id" -p "$parent" -m "$msg")
          else
            commit=$(git -c user.name="knode-vhp-ruler" -c user.email="knode-vhp-ruler@users.noreply.github.com" commit-tree "$tree_id" -m "$msg")
          fi
          git push -q "$remote" "$commit:refs/heads/vhp-data"
          echo "$msg"
`;
fs.writeFileSync(root + ".github/workflows/vhp-ruler.yml", yml);
console.log("wrote .github/workflows/vhp-ruler.yml");
